// Generates js/cap-icons.js from lucide-react (ISC license): inline SVG bodies, 24x24, 1.6 stroke. Run: node tools/gen-icons.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.resolve(here, '../../../client/node_modules/lucide-react/dist/esm/icons')
const NAMES = ['camera','x','check','circle-check','circle-x','triangle-alert','circle-alert','info','scan-face','volume-2','volume-x','refresh-cw','send','square','map-pinned','locate-fixed','download','satellite','activity','gauge','wifi','wifi-off','route','ban','server','radio','chevron-down','chevron-up','chevron-right','loader-circle','layout-grid','flask-conical','shield-alert','user-round','ellipsis','bug','play','cloud-off','list-checks','rotate-ccw','smartphone','focus','sun','shield-check','map-pin','arrow-right','inbox','sliders-horizontal','clock','hand']
const out = {}
for (const n of NAMES) {
  const f = path.join(dir, n + '.mjs')
  if (!fs.existsSync(f)) { console.warn('missing', n); continue }
  const nodes = (await import(f)).__iconData.node
  out[n] = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')} />`).join('')
}
const js = `/* Generated by tools/gen-icons.mjs from lucide (ISC). cap-icon(name, cls) -> inline <svg>. */
(function () {
  var PATHS = ${JSON.stringify(out, null, 1)};
  window.CAP_ICONS = PATHS;
  window.ic = function (name, size, cls) {
    var body = PATHS[name];
    if (!body) return '';
    var s = size || 16;
    return '<svg class="cap-icon' + (cls ? ' ' + cls : '') + '" viewBox="0 0 24 24" width="' + s + '" height="' + s + '" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">' + body + '</svg>';
  };
})();
`
fs.writeFileSync(path.join(here, '../js/cap-icons.js'), js)
console.log('icons:', Object.keys(out).length)
