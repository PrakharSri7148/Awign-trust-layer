// Adds the few lucide icons the AI-scan step needs on top of ../capture-photo/js/cap-icons.js. Run: node tools/gen-icons.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.resolve(here, '../../../client/node_modules/lucide-react/dist/esm/icons')
const NAMES = ['brain-circuit', 'arrow-left', 'circle', 'circle-dot', 'image', 'hourglass', 'clock', 'shield-alert']
const out = {}
for (const n of NAMES) {
  const f = path.join(dir, n + '.mjs')
  if (!fs.existsSync(f)) { console.warn('missing', n); continue }
  const nodes = (await import(f)).__iconData.node
  out[n] = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')} />`).join('')
}
const js = `/* Generated by tools/gen-icons.mjs from lucide (ISC). Extra icons for the AI-scan step; loaded after ../capture-photo/js/cap-icons.js. */
(function () {
  var EXTRA = ${JSON.stringify(out, null, 1)};
  Object.keys(EXTRA).forEach(function (k) { if (!window.CAP_ICONS[k]) window.CAP_ICONS[k] = EXTRA[k]; });
})();
`
fs.writeFileSync(path.join(here, '../js/scan-icons.js'), js)
console.log('icons:', Object.keys(out).length)
