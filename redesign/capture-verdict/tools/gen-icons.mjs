// Generates js/cap-icons-extra.js: the few lucide icons the Verdict step needs on top of ../capture-photo/js/cap-icons.js. Run: node tools/gen-icons.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const here = path.dirname(fileURLToPath(import.meta.url))
const dir = path.resolve(here, '../../../client/node_modules/lucide-react/dist/esm/icons')
const NAMES = ['copy', 'minus']
const out = {}
for (const n of NAMES) {
  const nodes = (await import(path.join(dir, n + '.mjs'))).__iconData.node
  out[n] = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== 'key').map(([k, v]) => `${k}="${v}"`).join(' ')} />`).join('')
}
fs.writeFileSync(path.join(here, '../js/cap-icons-extra.js'), `/* Generated by tools/gen-icons.mjs from lucide (ISC). Adds to window.CAP_ICONS (loaded after ../capture-photo/js/cap-icons.js). */
(function () { var X = ${JSON.stringify(out, null, 1)}; Object.keys(X).forEach(function (k) { window.CAP_ICONS[k] = X[k]; }); })();
`)
console.log('icons:', Object.keys(out).join(', '))
