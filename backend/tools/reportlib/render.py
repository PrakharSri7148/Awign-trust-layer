            for title, errs, causes in (("Missed issue photos (false negatives)", t["false_negatives"], t["fn_causes"]), ("Good photos flagged (false positives)", t["false_positives"], t["fp_causes"])):
                out.append(f"**{title}: {len(errs)}**" + (" (grouped by the check's own reason: " + "; ".join(f"{c['cause']} x{c['n']}" for c in causes) + ")" if errs else ""))
