def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def rate(r, d=1):
    if r is None or r["value"] is None:
        return "n/a"
    return f"{r['k']}/{r['n']} = {pct(r['value'], d)} (95% CI {pct(r['lo'], d)}-{pct(r['hi'], d)})"


def auc(a):
    return "n/a" if a["value"] != a["value"] else f"{a['value']:.3f} (95% CI {a['lo']:.3f}-{a['hi']:.3f})"


def num(x, d=3):
    return "n/a" if x is None else (f"{x:.{d}g}" if abs(x) < 1000 else f"{x:.0f}")


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def small_flag(t):
    return "  **Indicative only: fewer than 30 in a class.**" if t["flagged_level"]["small_sample"] else ""


def confusion_md(c, pos_label, neg_label, flag_word):
    return table(["", f"{flag_word}", f"not {flag_word}"],
                 [[f"actually {pos_label}", f"TP {c['tp']}", f"FN {c['fn']}"], [f"actually {neg_label}", f"FP {c['fp']}", f"TN {c['tn']}"]])


