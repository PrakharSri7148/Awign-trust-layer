    out += ["", "### Duplicates", "",
            f"- Exact duplicates (same SHA-256): **{d['groups']} groups, {d['files_in_groups']} files**. Across folders: "
            + (", ".join(f"`{k}` ({v} files)" for k, v in d["cross_folder_pairs"].items()) or "none") + ". "
            "Within a folder (extra copies): " + (", ".join(f"`{k}` {v}" for k, v in d["within_folder_extra_copies"].items()) or "none") + ".",
            f"- **{inv['n_excluded']} files are excluded** from every number below (the earliest folder keeps a duplicated file; a file in both a good and a bad folder is dropped from both)."]
