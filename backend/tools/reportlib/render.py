def _pad_table(m, title_prefix):
    rows = [[k, rate(v, 0)] for k, v in m["apcer_by_type"].items()]
    return table(["attack type", "APCER: attacks ACCEPTED"], rows) + "\n\n" + \
        f"{title_prefix}: **APCER (worst attack type) {pct(m['apcer'])}** ({m['apcer_worst_type']}); **BPCER {rate(m['bpcer'], 1)}**; **ACER {pct(m['acer'])}**."


