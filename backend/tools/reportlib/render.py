def weakest(data):
    """Ranked list of the weakest areas, computed from the numbers where possible."""
    items = []
    items.append((100, "**Liveness / anti-spoofing is unmeasured on real data.** Without `live_selfies/` and `spoof_*` samples there is no real APCER/BPCER; the thresholds are starting values." if not data["liveness"]["evaluated"] else "Liveness numbers depend on a small sample; see section 4 for the intervals."))
    items.append((95, "**The fraud classifier has never seen real data.** Its accuracy is a property of the simulator (section 5b); a shifted world already costs it noticeable accuracy."))
    fu = data.get("fusion") or {}
    if fu.get("evaluations"):
        if not fu["real"]["evaluated"]:
            items.append((96, "**Sensor fusion has no real trace behind it.** Every motion/network number is SYNTHETIC (section 5b); the thresholds in `fusion.json` are uncalibrated starting values. Record traces into `Sensor-fusion/samples/`."))
        hg = fu["groups"]["shifted_world"].get("hard_genuine", {}).get("false_flag")
        if hg and hg["value"] is not None and hg["value"] > 0.05:
            items.append((92, f"**Honest workers in awkward situations get flagged**: {rate(hg, 0)} of the hard-genuine scenarios in the shifted simulated world (SYNTHETIC; indoor drift, tunnels, smooth highways, VPN...)."))
        fh = fu["groups"]["different_seed"].get("fraud_hard", {}).get("recall")
        if fh and fh["value"] is not None and fh["value"] < 0.8:
            items.append((91, f"**Replayed motion on a frozen mock location and wrong-area networks are only partly caught**: {rate(fh, 0)} (SYNTHETIC, by construction the hardest spoofs)."))
    for e in data["checks"]:
        for prov, t in e["tables"].items():
            if prov == "SYNTHETIC":
                continue
            f, fl = t["flagged_level"], t["fail_level"]
            if f["recall"]["value"] is not None and f["recall"]["value"] < 0.8:
                items.append((80 + (1 - f["recall"]["value"]) * 10, f"**{e['title']} misses real issues**: recall {rate(f['recall'], 0)} (REAL)."))
            if fl["false_positive_rate"]["value"] and fl["false_positive_rate"]["value"] > 0.03:
                items.append((85, f"**{e['title']} blocks good photos**: {rate(fl['false_positive_rate'], 1)} (REAL, target <= 3%)."))
            if f["false_positive_rate"]["value"] and f["false_positive_rate"]["value"] > 0.08:
                items.append((60, f"{e['title']} flags {rate(f['false_positive_rate'], 0)} of good photos (REAL; non-blocking unless it fails)."))
            if t["auc"]["lo"] == t["auc"]["lo"] and t["auc"]["lo"] < 0.8:
                items.append((70, f"{e['title']} separates good from issue photos weakly: AUC lower bound {t['auc']['lo']:.2f} (REAL)."))
    no_real = [e["title"] for e in data["checks"] if "REAL" not in e["tables"]]
    if no_real:
        items.append((90, "**No real positive examples for:** " + ", ".join(no_real) + ". They are validated on synthetic degradations only, which cannot show how real photos of these problems behave."))
    faces = data["face"]["folders"]
    if "good_selfies" not in faces:
        items.append((88, "**Face check false-reject rate on clear faces is unknown** (no `good_selfies/`), and the face check can block a face-required task."))
    items.append((75, "**The `good/` set is stock photography**, sharper and more uniform than worker phone photos, so false-flag rates on real worker photos are probably higher than shown."))
    items.append((65, "No fairness slice evidence (skin tone, lighting, head coverings, device) exists in any section; the samples carry no such tags."))
    return [t for _s, t in sorted(items, key=lambda x: -x[0])]


